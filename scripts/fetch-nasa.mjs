// Fetch a dated snapshot of NASA open data used by the game (space weather and near-Earth objects).
// Writes src/data/nasa.ts. Run: node scripts/fetch-nasa.mjs   (uses DEMO_KEY unless NASA_API_KEY is set)
import { writeFileSync } from 'node:fs';
import { parseDonkiCme, parseDonkiGst, parseNeoWs, parseEonet } from '../src/net/nasa-parse.ts';

const KEY = process.env.NASA_API_KEY || 'DEMO_KEY';
const day = (d) => d.toISOString().slice(0, 10);
const now = new Date(), from = (n) => day(new Date(now.getTime() - n * 864e5));
const get = async (url) => { const r = await fetch(url); if (!r.ok) throw new Error(`${r.status} ${url.replace(KEY, '***')}`); return r.json(); };

const [cme, gst, neo, eonet] = await Promise.all([
  get(`https://api.nasa.gov/DONKI/CME?startDate=${from(45)}&endDate=${day(now)}&api_key=${KEY}`),
  get(`https://api.nasa.gov/DONKI/GST?startDate=${from(59)}&endDate=${day(now)}&api_key=${KEY}`),
  get(`https://api.nasa.gov/neo/rest/v1/feed?start_date=${day(now)}&end_date=${day(new Date(now.getTime() + 6 * 864e5))}&api_key=${KEY}`),
  get('https://eonet.gsfc.nasa.gov/api/v3/events?status=open&limit=60'),
]);
const out = { date: day(now), cme: parseDonkiCme(cme), gst: parseDonkiGst(gst), neo: parseNeoWs(neo), eonet: parseEonet(eonet) };
writeFileSync('src/data/nasa.ts', `// Generated by scripts/fetch-nasa.mjs from NASA DONKI, NeoWs and EONET on ${out.date}. Do not edit.\nexport const NASA = ${JSON.stringify(out, null, 1)};\n`);
console.log({ date: out.date, cme: out.cme.length, gst: out.gst.length, neo: out.neo.length, eonet: out.eonet.length });
