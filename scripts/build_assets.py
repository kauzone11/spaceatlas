"""Builds src/data/assets.ts (textures, portraits, Bennu mesh) and src/data/snapshot.ts (NASA data) from raw/."""
import json, base64, io, struct, os
from PIL import Image
R = os.path.join(os.path.dirname(__file__), '..', 'raw'); OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data')
def jpg(im, q=80):
    b = io.BytesIO(); im.convert('RGB').save(b, 'JPEG', quality=q, optimize=True); return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
tex = {
 'earth': jpg(Image.open(f'{R}/earth_svs.png').resize((2048, 1024), Image.LANCZOS), 80),
 'moon': jpg(Image.open(f'{R}/moon.tif').resize((2048, 1024), Image.LANCZOS), 78),
 'mars': jpg(Image.open(f'{R}/mars.jpg'), 82),
}
# mentors of the four playable crew members (src/data/crew.ts)
crops = {'ochoa': ('jsc2014e037863.jpg', .50, .30, .24), 'watkins': ('jsc2026e035015_alt.jpg', .51, .125, .10), 'chang': ('S97-06573.jpg', .5, .3, .25),
         'koch': ('jsc2018e095073_alt.jpg', .52, .20, .19)}
por = {}
for k, (f, cx, cy, h) in crops.items():
    im = Image.open(f'{R}/p/{f}').convert('RGB'); w, hh = im.size; x, y, r = cx * w, cy * hh, h * w
    por[k] = jpg(im.crop((int(x - r), int(y - r), int(x + r), int(y + r))).resize((176, 176), Image.LANCZOS), 80)
# Bennu shape model -> quantized int16 positions + uint16 indices
d = open(f'{R}/bennu.glb', 'rb').read(); l = struct.unpack('<I', d[12:16])[0]; j = json.loads(d[20:20 + l]); bin0 = d[20 + l + 8:]
def acc(i):
    a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]; off = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    n = a['count'] * {'VEC3': 3, 'SCALAR': 1}[a['type']]; fmt = {5126: 'f', 5123: 'H', 5125: 'I'}[a['componentType']]
    return struct.unpack('<' + str(n) + fmt, bin0[off:off + n * struct.calcsize(fmt)])
p = j['meshes'][0]['primitives'][0]; pos = acc(p['attributes']['POSITION']); idx = acc(p['indices'])
m = max(abs(v) for v in pos); q = struct.pack('<' + str(len(pos)) + 'h', *[int(round(v / m * 32767)) for v in pos])
bennu = {'pos': base64.b64encode(q).decode(), 'idx': base64.b64encode(struct.pack('<' + str(len(idx)) + 'H', *idx)).decode()}
with open(f'{OUT}/assets.ts', 'w') as f:
    f.write('// Generated by scripts/build_assets.py from NASA public-domain sources. Do not edit.\n')
    # planet textures live in src/data/worlds.ts (scripts/build_worlds.py)
    f.write('export const PORTRAIT: Record<string, string> = ' + json.dumps(por) + ';\n')
    f.write('export const BENNU = ' + json.dumps(bennu) + ';\n')
# ---- data snapshot
ev = json.load(open(f'{R}/eonet.json'))['events']; seen = {}; events = []
for e in sorted(ev, key=lambda e: e['geometry'][-1]['date'], reverse=True):
    c = e['categories'][0]['id']
    if seen.get(c, 0) >= (6 if c == 'wildfires' else 3): continue
    seen[c] = seen.get(c, 0) + 1; g = e['geometry'][-1]
    co = g['coordinates']
    while isinstance(co[0], list): co = co[0]
    events.append({'id': e['id'], 'title': e['title'], 'cat': c, 'date': g['date'][:10], 'lon': round(co[0], 2), 'lat': round(co[1], 2), 'src': e['sources'][0]['id']})
c = json.load(open(f'{R}/cad.json')); F = c['fields']; cad = []
for r in c['data'][:10]:
    o = dict(zip(F, r)); cad.append({'des': o['des'], 'date': o['cd'], 'distAu': round(float(o['dist']), 6), 'vRel': round(float(o['v_rel']), 2), 'h': float(o['h'])})
nh = []
for x in json.load(open(f'{R}/nhats_detail.json')):
    t = x['traj']
    if t['launch'] < '2027': continue
    nh.append({'des': x['des'], 'h': float(x['h']), 'minSize': float(x['min_size']), 'maxSize': float(x['max_size']), 'launch': t['launch'], 'c3': float(t['c3']), 'dvArr': float(t['vrel_arr_neo']), 'durOut': int(t['dur_out'])})
with open(f'{OUT}/snapshot.ts', 'w') as f:
    f.write('// Generated by scripts/build_assets.py. Real NASA data captured on the date below.\n')
    f.write('export const SNAPSHOT = ' + json.dumps({'date': '2026-11-12', 'eonet': events, 'cad': cad, 'nhats': nh}, indent=1) + ';\n')
print({k: len(v) // 1024 for k, v in tex.items()}, len(bennu['pos']) // 1024, len(events), len(cad), nh)
